DEFAULT_SEC_CH_UA = {
    "sec-ch-ua": '"Chromium";v="128", "Not;A=Brand";v="24", "Google Chrome";v="128"',
    "sec-ch-ua-mobile": "?0",
    "sec-ch-ua-platform": '"macOS"',
}


class UserAgentRotator:
    """Provides rotating realistic User-Agents and realistic browser headers."""

    def __init__(self, mode: Literal["desktop", "mobile", "any"] = "desktop", custom_list: list[str] | None = None):
        self.mode = mode
        if custom_list:
            self._pool = custom_list
        elif mode == "desktop":
            self._pool = DESKTOP_USER_AGENTS
        elif mode == "mobile":
            self._pool = MOBILE_USER_AGENTS
        else:
            self._pool = DESKTOP_USER_AGENTS + MOBILE_USER_AGENTS

    def get_user_agent(self) -> str:
        """Return a random User-Agent from the selected pool."""
        return random.choice(self._pool)

    def get_browser_headers(self) -> dict[str, str]:
        """Generate a complete set of standard browser headers including Accept, Language, and Sec headers."""
        ua = self.get_user_agent()
        headers = {
            "User-Agent": ua,
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8",
            "Accept-Language": "en-US,en;q=0.9",
            "Connection": "keep-alive",
            "Upgrade-Insecure-Requests": "1",
            "Sec-Fetch-Dest": "document",
            "Sec-Fetch-Mode": "navigate",
            "Sec-Fetch-Site": "none",
            "Sec-Fetch-User": "?1",
        }
        if "Chrome" in ua or "Edg" in ua:
            headers.update(DEFAULT_SEC_CH_UA)
        return headers
